#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Run a real OCR evaluation with Tesseract over the images generated by
ocr_web_generator.py. The OCR language is auto-detected from the dataset's
metadata.json (Arabic/ara, Chinese/chi_sim, English/eng), or set explicitly
with --lang.

Pipeline:
  1) run `tesseract --psm 6 -l <lang>` (TSV output) on every images/*.png
  2) parse the TSV into word-level OCR results (text + bbox in pixel coords)
  3) compare against ground_truth/*.json with evaluate_ocr.OCREvaluator
     -> CER / WER / word-box mean IoU

Usage:
  python run_eval_tesseract.py --dataset ./ocr_dataset_ar
  python run_eval_tesseract.py --dataset ./ocr_dataset_zh
  python run_eval_tesseract.py --dataset ./ocr_dataset_en --lang en --psm 11

Dependencies:
  pip install editdistance        # CER/WER
  Tesseract must be installed and include the matching .traineddata
  (ara / chi_sim / eng)
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

# language code -> Tesseract traineddata name (matches ocr_web_generator.py LANGUAGES)
LANG_CODE_TO_TESSERACT = {"ar": "ara", "zh": "chi_sim", "en": "eng"}
LANG_NAME_TO_TESSERACT = {"Arabic": "ara", "Chinese": "chi_sim", "English": "eng"}


def detect_tesseract_lang(dataset_dir, lang_arg):
    """Resolve the Tesseract language: an explicit --lang ar|zh|en, or auto-
    detect from the dataset metadata.json (falls back to Arabic)."""
    if lang_arg in LANG_CODE_TO_TESSERACT:
        return LANG_CODE_TO_TESSERACT[lang_arg]
    meta = Path(dataset_dir) / "metadata.json"
    if meta.exists():
        try:
            with open(meta, encoding="utf-8") as f:
                info = json.load(f).get("dataset_info", {})
            name = info.get("language")
            if name in LANG_NAME_TO_TESSERACT:
                return LANG_NAME_TO_TESSERACT[name]
            code = info.get("language_code")
            if code in LANG_CODE_TO_TESSERACT:
                return LANG_CODE_TO_TESSERACT[code]
        except Exception:
            pass
    print("[warning] language not detected from metadata.json, defaulting to Arabic (ara)")
    return "ara"


def run_tesseract_tsv(image_path, tesseract="tesseract", lang="ara", psm=6):
    """Run tesseract and return the level==5 (word) TSV rows."""
    cmd = [tesseract, str(image_path), "-", "-l", lang,
           "--psm", str(psm), "tsv"]
    out = subprocess.run(cmd, capture_output=True, text=True,
                         encoding="utf-8", errors="replace")
    if out.returncode != 0:
        print(f"  [warning] tesseract failed: {out.stderr[:200]}")
        return []
    rows = []
    lines = out.stdout.splitlines()
    if not lines:
        return []
    header = lines[0].split("\t")
    for ln in lines[1:]:
        cols = ln.split("\t")
        if len(cols) < len(header):
            continue
        rec = dict(zip(header, cols))
        try:
            if int(rec["level"]) == 5 and float(rec["conf"]) > -1:
                text = rec["text"].strip()
                if text:
                    rows.append({
                        "text": text,
                        "left": float(rec["left"]),
                        "top": float(rec["top"]),
                        "width": float(rec["width"]),
                        "height": float(rec["height"]),
                        "conf": float(rec["conf"]),
                    })
        except (ValueError, KeyError):
            continue
    return rows


def tesseract_to_ocr_output(rows):
    """Convert the TSV word rows into the {text, words:[{text,bbox}]} shape
    expected by OCREvaluator. TSV row order is Tesseract's reading order
    (for Arabic RTL: line by line, right to left within a line)."""
    words = []
    for r in rows:
        words.append({
            "text": r["text"],
            "bbox": {"x": r["left"], "y": r["top"],
                     "width": r["width"], "height": r["height"]},
        })
    text = " ".join(w["text"] for w in words)
    return {"text": text, "words": words}


def main():
    ap = argparse.ArgumentParser(description="Tesseract OCR evaluation")
    ap.add_argument("--dataset", default="./ocr_dataset_ar")
    ap.add_argument("--tesseract", default="C:/Program Files/Tesseract-OCR/tesseract.exe")
    ap.add_argument("--lang", choices=["auto", "ar", "zh", "en"], default="auto",
                    help="OCR language: auto (read from dataset metadata, default), "
                         "ar (Arabic/ara), zh (Chinese/chi_sim), en (English/eng)")
    ap.add_argument("--psm", type=int, default=6)
    args = ap.parse_args()

    ds = Path(args.dataset)
    images_dir = ds / "images"
    gt_dir = ds / "ground_truth"

    tesseract_lang = detect_tesseract_lang(ds, args.lang)
    print(f"Using Tesseract language: {tesseract_lang}")

    from evaluate_ocr import OCREvaluator
    evaluator = OCREvaluator(str(ds))

    results = []
    for img_path in sorted(images_dir.glob("*.png")):
        gt_file = gt_dir / (img_path.stem + ".json")
        if not gt_file.exists():
            print(f"[skip] no ground truth for {img_path.name}")
            continue

        rows = run_tesseract_tsv(img_path, args.tesseract, tesseract_lang, args.psm)
        ocr_out = tesseract_to_ocr_output(rows)
        gt = evaluator.load_ground_truth(str(gt_file))

        res = evaluator.evaluate_sample(str(gt_file), ocr_out)
        res["image"] = img_path.name
        res["gt_text"] = gt["text"]
        res["pred_text"] = ocr_out["text"]
        results.append(res)

        print(f"{img_path.name}: CER={res['cer']:.3f} WER={res['wer']:.3f} "
              f"meanIoU={res['mean_iou']:.3f} | GT={gt['text'][:24]!r}")

    if not results:
        print("No samples to evaluate.")
        return

    report = evaluator.generate_report(results)
    print("\n===== Summary =====")
    print(f"Samples        : {report['total_samples']}")
    print(f"Mean CER       : {report['mean_cer']:.4f}")
    print(f"Mean WER       : {report['mean_wer']:.4f}")
    print(f"Mean box IoU   : {report['mean_iou']:.4f}")

    out_path = ds / "eval_report.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    print(f"Report saved: {out_path}")


if __name__ == "__main__":
    main()
